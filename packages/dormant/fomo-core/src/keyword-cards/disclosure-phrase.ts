/**
 * WO-RESET-05 §3-1 · DETAIL-04 — 공시 제목을 **사람 말**로 바꾸고 **뜻을 풀어 준다.**
 * 순수 함수(네트워크·시간·난수 0).
 *
 * ## 왜 필요한가
 *
 * 상세의 「왜 지금 사는가」에 공시 제목이 **원문 그대로** 올라간다:
 *
 * ```
 * 임원ㆍ주요주주특정증권등소유상황보고서
 * 주식등의대량보유상황보고서(일반)
 * 타인에대한담보제공결정
 * ```
 *
 * 이건 근거가 아니라 **금융감독원 서식 이름**이다. 읽는 사람이 무슨 일이 있었는지 모른다.
 *
 * ## 한 줄 번역으로도 부족했다 (DETAIL-04, 2026-09-04 광혁 지시)
 *
 * 프로덕션 화면은 이렇게 나갔다:
 *
 * ```
 * 8월 14일  반년 치 실적을 냈어요        공시 원문 →
 * 8월 31일  누군가 지분 5% 이상을 신고했어요  공시 원문 →
 * ```
 *
 * 서식 이름은 우리말이 됐지만 **여전히 단어 나열이다.** `지분 5% 이상을 신고했어요` 가
 * 무슨 뜻인지(왜 5%인가, 누가 무엇을 알려야 하는가)는 그대로 남아 있고, 그걸 알려면
 * `공시 원문 →` 을 눌러 DART 서식을 읽어야 한다. **아무도 그걸 누르지 않는다** —
 * 눌러도 원문은 읽기 어렵다(`disclosure-figures` 머리말과 같은 판단이다).
 *
 * 그래서 링크로 떠넘기지 않고 **우리가 한 줄 더 풀어서 쓴다**(`meaning`).
 *
 * ## `meaning` 은 회사 사실이 아니라 **서식의 뜻**이다
 *
 * 이 구분이 이 파일의 핵심 규칙이다:
 *
 * | | 무엇인가 | 어디서 오나 |
 * |---|---|---|
 * | `text` | 이 회사에 **무슨 일이 있었나** | 제목(서식 이름 + 제목이 들고 온 수치) |
 * | `meaning` | 그 서식이 **제도적으로 무엇인가** | 법·규정에 고정된 상수 |
 *
 * `meaning` 은 종목마다 달라지지 않는다 — `주식등의대량보유상황보고서` 는 어느 회사든
 * 5% 룰 보고서다. 그래서 이걸 쓰는 것은 **추측이 아니라 사전(dictionary)** 이다. 반대로
 * 이 회사의 금액·방향·의도는 본문에 있고 우리는 본문을 저장하지 않으므로
 * **절대 쓰지 않는다**(WO-RESET-02 하지 말 것 1번).
 *
 * 그래서 `meaning` 에 허용되는 것은 딱 세 가지다:
 * ① 그 서식을 내야 하는 **요건**(누가·언제·얼마 넘으면),
 * ② 그 사건의 **기계적 귀결**(소각하면 주식 수가 줄고, 전환되면 늘어난다),
 * ③ **제목만으로는 알 수 없는 것**(사는 계획인지 파는 계획인지).
 *
 * ③ 이 특히 중요하다 — 모르는 것을 모른다고 쓰는 자리가 없으면, 읽는 사람이 빈칸을
 * 자기 기대로 채운다.
 *
 * ## 번역이지 요약이 아니다
 *
 * 한 서식은 **한 가지 사건**을 뜻한다(그래서 서식이 나뉘어 있다). 그 사건을 우리말로 옮기는
 * 것은 해석이 아니라 번역이다. 제목에 없는 것(금액·평가·전망)은 `text` 에 **절대 넣지 않는다.**
 *
 * ## 제목이 들고 있던 숫자는 버리지 않는다
 *
 * 어떤 제목은 뒤에 실제 수치를 달고 온다 — `단일판매ㆍ공급계약체결 · 계약금액 320억`.
 * 서식 이름만 옮기고 그 숫자를 떨어뜨리면 **번역이 아니라 손실**이다. 제목에 있던 것은
 * 지어낸 것이 아니므로 뒤에 그대로 붙인다. 서식 이름 안의 중점(`단일판매ㆍ공급계약`)과
 * 부기 구분은 **공백 있는 구분자**로 가른다 — 서식 이름은 공백 없이 붙여 쓴다.
 *
 * ## 표에 없으면 원문 그대로
 *
 * 억지로 비슷한 칸에 밀어 넣지 않는다. 모르는 서식은 **원문 제목이 정직하다** —
 * 틀린 우리말보다 낫다. 표에 없어서 원문으로 나간 비율은 계측해서 보고한다.
 *
 * ## 사람 검토
 *
 * 이 표의 정본은 `docs/wo/DISCLOSURE_PHRASEBOOK.md` 다. 문구를 바꿀 때는 그 문서와 함께
 * 바꾼다 — 코드에만 있으면 검토할 수 없다. 테스트가 둘의 일치를 강제한다.
 */

/**
 * 번역 결과. `translated: false` 면 원문 제목을 그대로 쓴 것이다(계측용).
 * `meaning` 은 표에 있는 서식일 때만 붙는다 — 모르는 서식의 뜻을 지어내지 않는다.
 */
export interface DisclosurePhrase {
  text: string;
  translated: boolean;
  /** 서식의 뜻 한 줄. 이 회사 사실이 아니라 **제도 설명**이다(위 표). */
  meaning?: string;
}

