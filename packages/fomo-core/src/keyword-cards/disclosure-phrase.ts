/**
 * 공시 제목을 사람 말로. 표에 없으면 **원문 제목을 그대로** 돌려준다(`translated: false`).
 *
 * @param title DART `report_nm` 원문. 공백은 무시하고 맞춘다(원문 표기가 들쭉날쭉하다).
 */
export function disclosurePhrase(title: string | undefined | null): DisclosurePhrase {
  const raw = title?.trim() ?? "";
  if (!raw) return { text: "", translated: false };

  const corrected = CORRECTION_PREFIX.test(raw);
  const full = raw.replace(CORRECTION_PREFIX, "").trim();
  /**
   * 서식 이름과 **뒤에 붙은 실제 수치**를 가른다.
   *
   * 구분자만으로는 못 가른다 — 어떤 원문은 서식 이름 자체를 띄어 쓴다
   * (`임원 ㆍ 주요주주 특정증권등 소유상황보고서`). 그래서 **마지막 조각에 숫자가 있을 때만**
   * 부기로 본다. 여기서 지키려는 것이 숫자이므로 판별 기준도 숫자다.
   */
  const parts = full.split(/\s+[·ㆍ|]\s+/);
  const tail = parts.length > 1 ? parts[parts.length - 1]!.trim() : "";
  const hasDetail = tail.length > 0 && /\d/.test(tail);
  const body = (hasDetail ? parts.slice(0, -1).join(" ㆍ ") : full).trim();
  const detail = hasDetail ? tail : "";
  // 공백·중점 표기가 원문마다 달라서(`임원ㆍ주요주주` / `임원·주요주주` / `임원 · 주요주주`)
  // 공백만 지우고 맞춘다. 중점 종류는 정규식이 함께 받는다.
  const needle = body.replace(TRAILING_PAREN, "").replace(/\s+/g, "");

  for (const [pattern, phrase] of RULES) {
    if (pattern.test(needle)) {
      // 제목이 들고 있던 수치는 붙인다. 정정이라는 사실도 버리지 않는다.
      const withDetail = detail ? `${phrase} · ${detail}` : phrase;
      return { text: corrected ? `${withDetail} (정정)` : withDetail, translated: true };
    }
  }
  return { text: raw, translated: false };
}
